"""Build per-signature native shims for ABI shapes Frida cannot marshal.

Frida can only replace functions whose arguments/returns are scalars.  A guard
that targets a function taking or returning a struct by value needs a small
native wrapper with the exact C signature:

    <return_t> __vg_shim_<n>(<args>) {
        slots = <flattened arguments>;
        if (vg_run(program, slots, ...) != 0) { <block_c> }
        return original(<args>);
    }

The wrapper is compiled next to the bundle (trusted build artifact) and
installed with Interceptor.replace(target, shim_entry).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys

_SCALAR_KINDS = {'int', 'uint', 'int64', 'uint64', 'pointer', 'float', 'double'}


def _slot_lines(args: list[dict]) -> list[str]:
    lines: list[str] = []
    for index, arg in enumerate(args):
        kind = arg.get('kind')
        name = arg['name']
        if kind in ('int', 'uint', 'int64', 'uint64'):
            lines.append(f'    slots[{index}] = (uint64_t)({name});')
        elif kind == 'pointer':
            lines.append(f'    slots[{index}] = (uint64_t)(uintptr_t)({name});')
        elif kind == 'float':
            lines.append(f'    {{ float v = (float)({name}); uint32_t b = 0; memcpy(&b, &v, 4); slots[{index}] = b; }}')
        elif kind == 'double':
            lines.append(f'    {{ double v = (double)({name}); uint64_t b = 0; memcpy(&b, &v, 8); slots[{index}] = b; }}')
        elif kind == 'struct':
            lines.append(f'    slots[{index}] = (uint64_t)(uintptr_t)&({name});')
        else:
            raise ValueError(f'unsupported shim argument kind: {kind!r}')
    return lines


def render(spec: dict) -> str:
    """Render the C source for one shim from a trusted spec document."""
    args = spec.get('args_c') or []
    if not isinstance(args, list) or len(args) > 6:
        raise ValueError('args_c must be a list of at most 6 arguments')
    if any(not isinstance(arg, dict) or 'name' not in arg or 'type' not in arg for arg in args):
        raise ValueError('each args_c entry needs name and type')
    return_c = spec.get('return_c')
    entry = spec.get('entry')
    block_c = spec.get('block_c')
    if not isinstance(return_c, str) or not return_c.strip():
        raise ValueError('return_c is required')
    if not isinstance(entry, str) or not entry.isidentifier():
        raise ValueError('entry must be a C identifier')
    if not isinstance(block_c, str) or not block_c.strip():
        raise ValueError('block_c is required')
    declarations = ', '.join(f"{arg['type']} {arg['name']}" for arg in args) or 'void'
    names = ', '.join(arg['name'] for arg in args)
    call = f'((vg_original_fn)vg_original)({names})'
    pass_statement = f'return {call};' if return_c.strip() != 'void' else f'{call}; return;'
    slots = '\n'.join(_slot_lines(args))
    types = spec.get('types') or ''
    return f'''/* Generated by runtime/frida/shim.py; trusted patch build artifact. */
#include <stdint.h>
#include <string.h>

{types}

typedef int (*vg_run_fn)(void *program, uint64_t *args, uint64_t *slots,
                         unsigned limit, void *stats);
typedef {return_c} (*vg_original_fn)({declarations});

static void *vg_program = 0;
static unsigned vg_limit = 4096;
static void *vg_original = 0;
static vg_run_fn vg_run_ptr = 0;

__attribute__((visibility("default")))
void __vg_shim_bind(void *program, unsigned limit, void *run_ptr)
{{
    vg_program = program;
    vg_limit = limit;
    vg_run_ptr = (vg_run_fn)run_ptr;
}}

__attribute__((visibility("default")))
void __vg_shim_set_original(void *fn)
{{
    vg_original = fn;
}}

__attribute__((visibility("default")))
{return_c} {entry}({declarations})
{{
    uint64_t slots[6] = {{0}};
    uint64_t observations[16] = {{0}};
    uint64_t stats[3] = {{0}};
{slots}
    int decision = vg_run_ptr ? vg_run_ptr(vg_program, slots, observations, vg_limit, stats) : 2;
    if (decision != 0) {{
{block_c}
    }}
    {pass_statement}
}}
'''


def build(spec: dict, output: Path, cc: str | None = None, name: str | None = None) -> Path:
    """Compile a shim from a spec document and return the shared object path."""
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    compiler = cc or shutil.which('cc') or shutil.which('gcc')
    if not compiler:
        raise RuntimeError('C compiler missing; supply --cc')
    entry = spec['entry']
    source = output / (name or f'{entry}.c')
    library = output / (name or f'{entry}.so')
    source.write_text(render(spec), encoding='utf-8')
    subprocess.run([compiler, '-std=c11', '-O2', '-g', '-shared', '-fPIC',
                    str(source), '-o', str(library)], check=True)
    return library


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--spec', type=Path, required=True, help='JSON shim specification')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--cc')
    args = parser.parse_args()
    spec = json.loads(args.spec.read_text(encoding='utf-8'))
    print(build(spec, args.output, args.cc))


if __name__ == '__main__':
    main()
